package dev.viridianengineering.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import dev.viridianengineering.ViridianEngineering;
import net.minecraft.client.Minecraft;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.decoration.ArmorStand;

import java.util.EnumMap;
import java.util.Map;

/**
 * The worn Sylvan armor as a real 3D model (like Botania's Terrasteel set): geometry from
 * {@link SylvanArmorGeometry} (generated by tools/gen_sylvan_armor.py), texture
 * textures/models/armor/sylvan_3d.png. One instance per slot shows only that slot's parts; the
 * player's pose is copied onto it by NeoForge before it renders.
 */
public class SylvanArmorModel extends HumanoidModel<LivingEntity> {

    public static final ModelLayerLocation OUTER = new ModelLayerLocation(ViridianEngineering.asResource("sylvan_armor"), "outer");
    public static final ModelLayerLocation INNER = new ModelLayerLocation(ViridianEngineering.asResource("sylvan_armor"), "inner");
    public static final ResourceLocation TEXTURE = ViridianEngineering.asResource("textures/models/armor/sylvan_3d.png");

    private static final Map<EquipmentSlot, SylvanArmorModel> MODELS = new EnumMap<>(EquipmentSlot.class);

    private final EquipmentSlot slot;

    public SylvanArmorModel(ModelPart root, EquipmentSlot slot) {
        super(root);
        this.slot = slot;
    }

    public static LayerDefinition outerLayer() {
        return LayerDefinition.create(SylvanArmorGeometry.outer(), SylvanArmorGeometry.TEX_W, SylvanArmorGeometry.TEX_H);
    }

    public static LayerDefinition innerLayer() {
        return LayerDefinition.create(SylvanArmorGeometry.inner(), SylvanArmorGeometry.TEX_W, SylvanArmorGeometry.TEX_H);
    }

    /** Baked on first use (the geometry never changes, so it survives resource reloads). */
    public static SylvanArmorModel get(EquipmentSlot slot) {
        return MODELS.computeIfAbsent(slot, s -> new SylvanArmorModel(
                Minecraft.getInstance().getEntityModels().bakeLayer(s == EquipmentSlot.LEGS ? INNER : OUTER), s));
    }

    @Override
    public void setupAnim(LivingEntity entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        if (!(entity instanceof ArmorStand stand)) {
            super.setupAnim(entity, limbSwing, limbSwingAmount, ageInTicks, netHeadYaw, headPitch);
            return;
        }
        float k = (float) Math.PI / 180F;
        head.setRotation(k * stand.getHeadPose().getX(), k * stand.getHeadPose().getY(), k * stand.getHeadPose().getZ());
        body.setRotation(k * stand.getBodyPose().getX(), k * stand.getBodyPose().getY(), k * stand.getBodyPose().getZ());
        leftArm.setRotation(k * stand.getLeftArmPose().getX(), k * stand.getLeftArmPose().getY(), k * stand.getLeftArmPose().getZ());
        rightArm.setRotation(k * stand.getRightArmPose().getX(), k * stand.getRightArmPose().getY(), k * stand.getRightArmPose().getZ());
        leftLeg.setRotation(k * stand.getLeftLegPose().getX(), k * stand.getLeftLegPose().getY(), k * stand.getLeftLegPose().getZ());
        rightLeg.setRotation(k * stand.getRightLegPose().getX(), k * stand.getRightLegPose().getY(), k * stand.getRightLegPose().getZ());
        hat.copyFrom(head);
    }

    @Override
    public void renderToBuffer(PoseStack ms, VertexConsumer buffer, int light, int overlay, int color) {
        setAllVisible(false);
        switch (slot) {
            case HEAD -> head.visible = true;
            case CHEST -> { body.visible = true; rightArm.visible = true; leftArm.visible = true; }
            case LEGS -> { body.visible = true; rightLeg.visible = true; leftLeg.visible = true; }
            case FEET -> { rightLeg.visible = true; leftLeg.visible = true; }
            default -> {}
        }
        super.renderToBuffer(ms, buffer, light, overlay, color);
    }
}
